"""
Build a shared 150(+)-item persona/claim base for sycophancy-single (MCQ) and
sycophancy-long (open-ended) data, then generate real Qwen1.5-14B-Chat
responses for the persona and bare conditions in both formats.

Phase 1a — seed personas: for each of the ~32 unique claims found in
  data/Qwen1.5-14B-Chat/sycophancy-single/new_sycophancy_dataset.jsonl,
  invent a fresh persona + an opposing counter-claim (the claim text itself
  is kept verbatim from the source file).
Phase 1b — new-topic personas: generate additional persona+claim+
  opposing_claim items on fresh, non-NLP topics to build a large buffer of
  raw candidates.

Phase 1.5 — bare-stance probe + orientation resolve: claims generated by
  Qwen1.5-14B-Chat tend to already agree with Qwen1.5-14B-Chat's own bare
  (no-persona) opinion most of the time (self-consistency bias), so simply
  asking the bare model about "claim" rarely produces disagreement. Instead,
  cheaply probe the bare model's MCQ stance on BOTH claim and opposing_claim,
  and orient each candidate's persona toward whichever pole the bare model
  actually disagrees with. Candidates where the bare model agrees with (or
  can't answer) both poles are dropped here, before the expensive full
  response generation in phase 2 -- this is far cheaper than generating all
  four response variants and discovering the divergence never appears.

Phase 2 — response generation: for every resolved candidate, generate
  mcq_persona_response, long_persona_response and long_bare_response with
  Qwen1.5-14B-Chat via vLLM (mcq_bare_response is already known from the
  phase-1.5 probe, so it's reused rather than regenerated).

Output: data/<model>/sycophancy_base/candidates.jsonl -- one record per
resolved candidate with persona fields, the four prompts, and the four raw
responses.

Next step -- filter for genuine sycophancy divergence and write the final
training files:
  python filter_and_build_sycophancy_data.py --model_id Qwen/Qwen1.5-14B-Chat

Usage:
  python generate_sycophancy_base_150.py
"""

