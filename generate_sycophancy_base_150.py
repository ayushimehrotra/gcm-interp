def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model_id", default=QWEN_MODEL)
    ap.add_argument("--data_root", default="/home/ubuntu/gcm-interp/data")
    ap.add_argument(
        "--new_dataset_path",
        default="/home/ubuntu/gcm-interp/data/Qwen1.5-14B-Chat/sycophancy_base/new_sycophancy_dataset.jsonl",
    )
    ap.add_argument("--n_new_topics", type=int, default=1500,
                     help="Number of new-topic personas to generate (phase 1b), before the bare-stance resolve filter")
    ap.add_argument("--start_id_new", type=int, default=1001,
                     help="Starting id for new-topic personas (kept far from seed ids to avoid collision before renumbering)")
    ap.add_argument("--batch_size_seed", type=int, default=6)
    ap.add_argument("--batch_size_new", type=int, default=10)
    ap.add_argument("--num_parallel_new", type=int, default=20)
    ap.add_argument("--gpu_memory_utilization", type=float, default=0.45,
                     help="Kept conservative since other GPU jobs may be running concurrently")
    args = ap.parse_args()

    hf_token = os.environ.get("HF_TOKEN", "")
    model_name = args.model_id.split("/")[-1]
    base_dir = Path(args.data_root) / model_name / "sycophancy_base"
    base_dir.mkdir(parents=True, exist_ok=True)

    seed_path = base_dir / "seed_personas.jsonl"
    new_path = base_dir / "new_topic_personas.jsonl"
    resolved_path = base_dir / "resolved_candidates.jsonl"
    candidates_path = base_dir / "candidates.jsonl"

    print(f"Loading {args.model_id} via vLLM...")
    from vllm import LLM
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(args.model_id, token=hf_token if hf_token else None)
    llm = LLM(
        model=args.model_id,
        dtype="auto",
        # Bumped from 4096: the avoid-claims block injected into
        # NEW_TOPICS_PROMPT (phase 1b) can add ~1-2k tokens of prompt on top
        # of the up-to-4096-token completion budget.
        max_model_len=8192,
        gpu_memory_utilization=args.gpu_memory_utilization,
        seed=42,
    )

    # Phase 1a
    if seed_path.exists():
        print(f"\nPhase 1a: skipping (found {seed_path})")
        seed_personas = load_jsonl(seed_path)
    else:
        seed_claims = load_seed_claims(Path(args.new_dataset_path))
        print(f"\nPhase 1a: generating personas for {len(seed_claims)} seed claims from {args.new_dataset_path}...")
        seed_personas = phase1a_seed_personas(
            seed_claims, seed_path, llm, tokenizer, args.batch_size_seed
        )

    # Phase 1b
    if new_path.exists():
        print(f"\nPhase 1b: skipping (found {new_path})")
        new_personas = load_jsonl(new_path)
    else:
        print(f"\nPhase 1b: generating {args.n_new_topics} new-topic personas...")
        new_personas = phase1b_new_personas(
            args.n_new_topics, args.start_id_new, new_path, llm, tokenizer,
            args.batch_size_new, args.num_parallel_new,
            avoid_claims={p["claim"] for p in seed_personas},
        )

    # Merge + de-duplicate by claim (temperature-0.8 generation converges on
    # the same popular topics far more than the diversity instructions alone
    # prevent) + renumber sequentially (seed personas first, then new-topic)
    combined = seed_personas + new_personas
    seen_claims = set()
    all_personas = []
    for p in combined:
        key = p["claim"].strip().lower()
        if key not in seen_claims:
            seen_claims.add(key)
            all_personas.append(p)
    for i, p in enumerate(all_personas):
        p["id"] = i + 1

    print(f"\nTotal raw candidate personas: {len(combined)} ({len(all_personas)} unique by claim)")

    # Phase 1.5
    if resolved_path.exists():
        print(f"\nPhase 1.5: skipping (found {resolved_path})")
        resolved = load_jsonl(resolved_path)
    else:
        print(f"\nPhase 1.5: probing bare stance and resolving orientation...")
        resolved = phase1_5_resolve(all_personas, llm, tokenizer)
        for i, p in enumerate(resolved):
            p["id"] = i + 1
        write_jsonl(resolved_path, resolved)
        print(f"Saved {len(resolved)} resolved candidates -> {resolved_path}")

    print(f"\nResolved candidates proceeding to full response generation: {len(resolved)}")

    # Phase 2
    if candidates_path.exists():
        print(f"\nPhase 2: skipping (found {candidates_path})")
    else:
        print(f"\nPhase 2: generating persona MCQ + long-form responses for {len(resolved)} candidates...")
        phase2_generate_responses(resolved, candidates_path, llm, tokenizer)

    print(f"""
All done. Candidates written to: {candidates_path}

Next -- filter for genuine sycophancy divergence and build the final training files:
  cd /home/ubuntu/gcm-interp
  source .venv/bin/activate
  export LD_LIBRARY_PATH="${{LD_LIBRARY_PATH:-}}:/home/ubuntu/gcm-interp/.venv/lib/python3.10/site-packages/nvidia/cu13/lib"
  export VLLM_USE_DEEP_GEMM=0
  python filter_and_build_sycophancy_data.py --model_id {args.model_id}
""")


